#!/usr/bin/env node
// Regenerates src/prototype-v2-components.css from the prototype v2 stylesheet.
// The prototype is the authoritative design baseline (PRD §8.5); this keeps the
// component layer in sync instead of re-implementing it by hand.
//
// - Tokens live in prototype-v2-tokens.css and are skipped here.
// - Rules whose selectors collide with App markup (map SVG, welcome, focus
//   banner) or exist only for the prototype's review tooling are dropped.
// - `.app.m` rules (the prototype's phone layout class) become a
//   max-width: 760px media query, which is how the App switches layouts.
//
// - App v2 (#75) also gets src/v2/prototype-extra.css: the dropped focus card,
//   decision list, banner and palette rules, which v2 renders as in the
//   prototype. The map stays with the App's own port for now.
//
// Usage: node scripts/port-prototype-v2-components.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "../../../docs/product/fractalmind-app-prototype-v2/styles.css");
const target = resolve(here, "../src/prototype-v2-components.css");
const extraTarget = resolve(here, "../src/v2/prototype-extra.css");

const DROP = [
  /^:root/, // tokens
  /^\.app\b(?!\.m\b)/, /^\.device\b/, /^\.shell\.bare/, // prototype frame and phone preview
  /\.framed\b/,
  /^\.map\b/, /^\.strip\.map/, // the App draws its own map SVG
  /^\.banner\b/, /^\.basis\b/, /^\.focus\b/, /^\.focus-/, /^\.next\b/, // focus card the App does not use yet
  /^\.decisions\b/, // the App wraps decision cards in its own section
  /^\.legend\b/, // App map legend
  /^\.welcome\b/, /^\.w-/, // App welcome page keeps its own port
  /^\.rv-/, /^\.journey\b/, /^\.jr-dock\b/, /#review/, // review tooling
  /^\.palette\b/, // command palette is not implemented in the App
];

function statements(css) {
  // Splits top-level statements, keeping comments and @media blocks whole.
  const out = [];
  let i = 0;
  while (i < css.length) {
    if (/\s/.test(css[i])) { i++; continue; }
    if (css.startsWith("/*", i)) {
      const end = css.indexOf("*/", i) + 2;
      out.push({ kind: "comment", text: css.slice(i, end) });
      i = end;
      continue;
    }
    const open = css.indexOf("{", i);
    let depth = 0;
    let j = open;
    for (; j < css.length; j++) {
      if (css[j] === "{") depth++;
      else if (css[j] === "}" && --depth === 0) break;
    }
    const prelude = css.slice(i, open).trim();
    const body = css.slice(open + 1, j);
    out.push({ kind: prelude.startsWith("@") ? "at" : "rule", prelude, body });
    i = j + 1;
  }
  return out;
}

const EXTRA = [
  /^\.banner\b/, /^\.basis\b/, /^\.focus\b/, /^\.focus-/, /^\.next\b/,
  /^\.decisions\b/, /^\.legend\b/, /^\.palette\b/,
];
let extraMode = false;
const dropped = (selector) =>
  extraMode
    ? !EXTRA.some((re) => re.test(selector.trim()))
    : DROP.some((re) => re.test(selector.trim()));

function filterRule(prelude) {
  // Keep only the selectors in a list that are not dropped.
  const keep = prelude.split(",").map((s) => s.trim()).filter((s) => !dropped(s));
  return keep.length ? keep.join(", ") : null;
}

function generate(header) {
const desktop = [];
const phone = [];
function emitRule(prelude, body, into) {
  const selectors = filterRule(prelude);
  if (!selectors) return;
  const plain = selectors.split(", ").filter((s) => !s.startsWith(".app.m "));
  const mobile = selectors.split(", ").filter((s) => s.startsWith(".app.m ")).map((s) => s.slice(7)).filter((s) => !dropped(s));
  const decl = body.trim().replace(/\s+/g, " ");
  if (plain.length) into.push(`${plain.join(", ")} { ${decl} }`);
  if (mobile.length) phone.push(`${mobile.join(", ")} { ${decl} }`);
}

for (const s of statements(readFileSync(source, "utf8"))) {
  if (s.kind === "comment") {
    if (/^\/\* -+ /.test(s.text)) desktop.push(`\n${s.text}`);
    continue;
  }
  if (s.kind === "rule") { emitRule(s.prelude, s.body, desktop); continue; }
  if (s.prelude.startsWith("@keyframes")) {
    desktop.push(`${s.prelude} {${s.body.trim().replace(/\s+/g, " ")}}`);
    continue;
  }
  if (s.prelude.startsWith("@media")) {
    const inner = [];
    for (const r of statements(s.body)) if (r.kind === "rule") emitRule(r.prelude, r.body, inner);
    if (inner.length) desktop.push(`${s.prelude} {\n  ${inner.join("\n  ")}\n}`);
  }
}

return `${header}
${desktop.join("\n")}

/* Phone layout (prototype .app.m) */
@media (max-width: 760px) {
${phone.map((rule) => `  ${rule}`).join("\n")}
}
`;
}

const text = generate(`/* Generated by scripts/port-prototype-v2-components.mjs from
 * docs/product/fractalmind-app-prototype-v2/styles.css. Do not edit by hand:
 * change the prototype, then regenerate. App-specific rules live in styles.css. */`);
extraMode = true;
const extra = generate(`/* Generated by scripts/port-prototype-v2-components.mjs from
 * docs/product/fractalmind-app-prototype-v2/styles.css for App v2: prototype
 * rules the App layer leaves out. Do not edit by hand. */`);

if (process.argv.includes("--check")) {
  const read = (file) => { try { return readFileSync(file, "utf8"); } catch { return ""; } };
  if (read(target) !== text || read(extraTarget) !== extra) {
    console.error("Prototype styles are out of date; run node scripts/port-prototype-v2-components.mjs");
    process.exit(1);
  }
} else {
  writeFileSync(target, text);
  writeFileSync(extraTarget, extra);
  console.log(`wrote ${target} and ${extraTarget}`);
}
