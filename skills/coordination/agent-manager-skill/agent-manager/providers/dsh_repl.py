#!/usr/bin/env python3
"""A small interactive bridge from agent-manager/tmux to DSH headless runs.

DeepSeek Harness deliberately has no supported interactive terminal UI.  Its
headless command accepts one task, emits NDJSON, and exits; this bridge turns
that command into a modest line-oriented REPL so agent-manager can continue to
use its normal tmux delivery and monitoring lifecycle.

The bridge owns the DSH session id in a small JSON file supplied by
agent-manager.  It deliberately never reads, writes, or prints credentials.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import signal
import subprocess
import sys
import tempfile
import termios
import tty
from dataclasses import dataclass
from typing import Any, Iterable, Optional, TextIO


PROMPT = "dsh❯ "
BUSY = "DSH busy…"
BRACKETED_PASTE_ON = "\x1b[?2004h"
BRACKETED_PASTE_OFF = "\x1b[?2004l"
PASTE_START = "\x1b[200~"
PASTE_END = "\x1b[201~"
DEFAULT_DSH_BINARY = "/Applications/DeepSeek Harness.app/Contents/Resources/runtime/cli/bin/dsh"
VALID_PERMISSION_MODES = {"read-only", "workspace-write", "danger-full-access"}


@dataclass
class ReplState:
    """The durable part of a DSH bridge session."""

    session_id: str = ""
    bootstrap_sent: bool = False

    @classmethod
    def load(cls, path: Path) -> "ReplState":
        try:
            raw = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError, TypeError):
            return cls()
        if not isinstance(raw, dict):
            return cls()
        return cls(
            session_id=str(raw.get("session_id") or ""),
            bootstrap_sent=bool(raw.get("bootstrap_sent")),
        )

    def save(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        payload = json.dumps(
            {"session_id": self.session_id, "bootstrap_sent": self.bootstrap_sent},
            sort_keys=True,
        ) + "\n"
        fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=str(path.parent))
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as handle:
                handle.write(payload)
            os.chmod(temporary, 0o600)
            os.replace(temporary, path)
        finally:
            try:
                os.unlink(temporary)
            except FileNotFoundError:
                pass


def default_dsh_binary() -> str:
    """Find DSH without depending on an interactive shell PATH."""
    override = os.environ.get("DSH_BIN", "").strip()
    if override:
        return override
    if Path(DEFAULT_DSH_BINARY).is_file():
        return DEFAULT_DSH_BINARY
    return "dsh"


def _yaml_scalar(value: str) -> str:
    """A deliberately tiny YAML string encoder for command-line values."""
    return json.dumps(value, ensure_ascii=False)


def make_model_overlay(provider: str, model: str) -> str:
    """Return the portable DSH default-model overlay, or no overlay at all.

    Model routes, aliases, reasoning controls, and credentials belong to a
    user-owned DSH profile or one of the caller's ``--patch`` files.  The only
    generic operation the bridge can safely synthesize is selecting a provider
    and model through DSH's built-in ``agent-default-model`` entry.
    """
    if not provider and not model:
        return ""
    if not provider or not model:
        raise ValueError("--provider and --model must be supplied together")
    return f"""# Generated by agent-manager dsh_repl.py; safe to replace.
- id: agent-default-model
  config:
    provider: {_yaml_scalar(provider)}
    model: {_yaml_scalar(model)}
"""


def write_model_overlay(state_file: Path, provider: str, model: str) -> Optional[Path]:
    """Write the bridge-owned, credential-free model selection overlay."""
    text = make_model_overlay(provider, model)
    if not text:
        return None
    path = state_file.with_suffix(".dsh-model-overlay.yml")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    try:
        os.chmod(path, 0o600)
    except OSError:
        pass
    return path


def _find_session_id(value: Any) -> str:
    """Extract an id from DSH's event shapes without coupling to one version."""
    if isinstance(value, dict):
        for key in ("session_id", "sessionId"):
            candidate = value.get(key)
            if isinstance(candidate, str) and candidate.strip():
                return candidate.strip()
        for nested in value.values():
            result = _find_session_id(nested)
            if result:
                return result
    elif isinstance(value, list):
        for nested in value:
            result = _find_session_id(nested)
            if result:
                return result
    return ""


def _event_text(event: Any) -> str:
    """Turn common DSH NDJSON events into stable, readable tmux output."""
    if not isinstance(event, dict):
        return ""
    event_type = str(event.get("type") or event.get("event") or "")
    lowered = event_type.lower()
    for key in ("text", "delta", "content", "message"):
        value = event.get(key)
        if isinstance(value, str) and value:
            if "error" in lowered:
                return f"DSH error: {value}"
            if "tool" in lowered:
                return f"DSH tool {event_type}: {value}"
            return value
    error = event.get("error")
    if error:
        if isinstance(error, dict):
            error = error.get("message") or error.get("code") or "request failed"
        return f"DSH error: {error}"
    if "tool" in lowered:
        name = event.get("name") or event.get("tool") or "call"
        return f"DSH tool {event_type}: {name}"
    return ""


def bootstrap_task(system_prompt: str, task: str, state: ReplState) -> str:
    """Put the manager's role instructions into the first persisted DSH turn."""
    if state.bootstrap_sent or not system_prompt:
        return task
    return (
        "The following agent-manager bootstrap instructions are authoritative for this "
        "session. Follow them for this and later tasks.\n\n"
        f"{system_prompt.rstrip()}\n\n"
        "--- End agent-manager bootstrap instructions ---\n\n"
        f"Task:\n{task}"
    )


class DshRunner:
    """Run one DSH headless task and persist the returned session id."""

    def __init__(
        self,
        *,
        dsh_bin: str,
        profile: str,
        state_file: Path,
        state: ReplState,
        overlay: Optional[Path],
        permission_mode: str,
        extra_patches: Iterable[str],
        output: TextIO,
    ) -> None:
        self.dsh_bin = dsh_bin
        self.profile = profile
        self.state_file = state_file
        self.state = state
        self.overlay = overlay
        self.permission_mode = permission_mode
        self.extra_patches = list(extra_patches)
        self.output = output
        self.current_process: Optional[subprocess.Popen[str]] = None
        self._previous_rendered = ""

    def command(self) -> list[str]:
        command = [self.dsh_bin, "--profile", self.profile]
        if self.overlay:
            command.extend(["--patch", str(self.overlay)])
        for patch in self.extra_patches:
            command.extend(["--patch", patch])
        command.append("--json")
        if self.state.session_id:
            command.extend(["--session-id", self.state.session_id])
        command.append("-")
        return command

    def interrupt(self) -> None:
        process = self.current_process
        if process is None or process.poll() is not None:
            return
        process.send_signal(signal.SIGINT)
        try:
            process.wait(timeout=3)
        except subprocess.TimeoutExpired:
            process.kill()

    def run(self, task: str, system_prompt: str) -> int:
        payload = bootstrap_task(system_prompt, task, self.state)
        environment = os.environ.copy()
        if self.permission_mode:
            environment["DSH_PERMISSION_MODE"] = self.permission_mode
        self.output.write(f"{BUSY}\n")
        self.output.flush()
        try:
            self.current_process = subprocess.Popen(
                self.command(),
                stdin=subprocess.PIPE,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                text=True,
                encoding="utf-8",
                errors="replace",
                env=environment,
            )
        except OSError as error:
            self.output.write(f"DSH error: could not start DSH: {error}\n")
            self.output.flush()
            return 127

        assert self.current_process.stdin is not None
        assert self.current_process.stdout is not None
        self.current_process.stdin.write(payload)
        self.current_process.stdin.close()
        emitted_text = False
        try:
            for line in self.current_process.stdout:
                line = line.strip()
                if not line:
                    continue
                try:
                    event = json.loads(line)
                except json.JSONDecodeError:
                    self.output.write(f"DSH: {line}\n")
                    self.output.flush()
                    continue
                session_id = _find_session_id(event)
                if session_id:
                    self.state.session_id = session_id
                    self.state.save(self.state_file)
                rendered = _event_text(event)
                if rendered:
                    # DSH versions commonly emit the terminal assistant text
                    # once as a stream update and once in a completion event.
                    # Suppress only an adjacent exact duplicate; repeated model
                    # prose separated by other output remains visible.
                    if rendered == self._previous_rendered:
                        continue
                    self.output.write(rendered)
                    if not rendered.endswith("\n"):
                        self.output.write("\n")
                    self.output.flush()
                    emitted_text = True
                    self._previous_rendered = rendered
        except KeyboardInterrupt:
            self.interrupt()
            self.output.write("DSH interrupted.\n")
            self.output.flush()
            return 130
        finally:
            process = self.current_process
            self.current_process = None

        result = process.wait()
        if result == 0:
            if not self.state.bootstrap_sent and system_prompt:
                self.state.bootstrap_sent = True
            self.state.save(self.state_file)
        elif not emitted_text:
            self.output.write(f"DSH error: task exited with status {result}\n")
            self.output.flush()
        return result


def _read_task_tty(stream: TextIO, output: TextIO) -> Optional[str]:
    """Read one task, preserving bracketed multi-line tmux pastes until Enter."""
    fd = stream.fileno()
    previous = termios.tcgetattr(fd)
    tty.setcbreak(fd)
    buffer: list[str] = []
    paste = False
    escape = ""
    try:
        output.write(PROMPT)
        output.flush()
        while True:
            char = stream.read(1)
            if char == "":
                return "".join(buffer) if buffer else None
            if escape or char == "\x1b":
                escape += char
                if PASTE_START.startswith(escape) or PASTE_END.startswith(escape):
                    if escape == PASTE_START:
                        paste = True
                        escape = ""
                    elif escape == PASTE_END:
                        paste = False
                        escape = ""
                    continue
                buffer.extend(escape)
                output.write(escape)
                output.flush()
                escape = ""
                continue
            if char in {"\r", "\n"} and not paste:
                output.write("\n")
                output.flush()
                return "".join(buffer).strip()
            if char in {"\x7f", "\b"} and not paste:
                if buffer:
                    buffer.pop()
                    output.write("\b \b")
                    output.flush()
                continue
            buffer.append(char)
            output.write(char)
            output.flush()
    finally:
        termios.tcsetattr(fd, termios.TCSADRAIN, previous)


def read_task(stream: TextIO, output: TextIO) -> Optional[str]:
    """Read a task from a terminal or a pipe (the latter is useful in tests)."""
    if stream.isatty():
        return _read_task_tty(stream, output)
    output.write(PROMPT)
    output.flush()
    line = stream.readline()
    return line.rstrip("\r\n") if line else None


def parse_args(argv: Optional[list[str]] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="agent-manager pseudo-REPL for DeepSeek Harness")
    parser.add_argument("--profile", required=True, help="DSH profile name")
    parser.add_argument("--state-file", required=True, type=Path, help="durable DSH session state JSON")
    parser.add_argument("--provider", default="", help="DSH provider id; requires --model")
    parser.add_argument("--model", default="", help="DSH model id; requires --provider")
    parser.add_argument("--permission-mode", choices=sorted(VALID_PERMISSION_MODES), default="")
    parser.add_argument("--patch", action="append", default=[], help="additional ephemeral DSH patch")
    parser.add_argument("--dsh-bin", default=default_dsh_binary(), help="DSH executable (test seam)")
    parser.add_argument(
        "--system-prompt",
        default="",
        help="agent-manager bootstrap text; persisted as the first DSH task, not a DSH system role",
    )
    return parser.parse_args(argv)


def main(argv: Optional[list[str]] = None, *, input_stream: TextIO = sys.stdin, output: TextIO = sys.stdout) -> int:
    args = parse_args(argv)
    if bool(args.provider) != bool(args.model):
        raise SystemExit("--provider and --model must be supplied together")
    state_file = args.state_file.expanduser().resolve()
    state = ReplState.load(state_file)
    overlay = write_model_overlay(state_file, args.provider, args.model)
    runner = DshRunner(
        dsh_bin=args.dsh_bin,
        profile=args.profile,
        state_file=state_file,
        state=state,
        overlay=overlay,
        permission_mode=args.permission_mode,
        extra_patches=args.patch,
        output=output,
    )
    output.write(BRACKETED_PASTE_ON)
    output.flush()
    try:
        while True:
            try:
                task = read_task(input_stream, output)
            except KeyboardInterrupt:
                output.write("\n")
                output.flush()
                continue
            if task is None:
                return 0
            if not task.strip():
                continue
            runner.run(task, args.system_prompt)
    finally:
        output.write(BRACKETED_PASTE_OFF)
        output.flush()


if __name__ == "__main__":
    raise SystemExit(main())
